function renderText(canvas, str, startX, startY, color, scale = 1, shadowColor = null) {
  str = str.toUpperCase();
  let cx = startX;
  const charWidth = 5;
  const charHeight = 7;
  const spacing = 1;

  for (let i = 0; i < str.length; i++) {
    const ch = str[i];
    const bitmap = FONT_5X7[ch] || FONT_5X7[' '];

    if (shadowColor) {
      // Draw 1px drop shadow
      for (let r = 0; r < charHeight; r++) {
        const row = bitmap[r];
        for (let c = 0; c < charWidth; c++) {
          if (row[c] === '1') {
            for (let dy = 0; dy < scale; dy++) {
              for (let dx = 0; dx < scale; dx++) {
                canvas.setPixel(cx + c * scale + dx + 1, startY + r * scale + dy + 1, shadowColor);
              }
            }
          }
        }
      }
    }

    for (let r = 0; r < charHeight; r++) {
      const row = bitmap[r];
      for (let c = 0; c < charWidth; c++) {
        if (row[c] === '1') {
          for (let dy = 0; dy < scale; dy++) {
            for (let dx = 0; dx < scale; dx++) {
              canvas.setPixel(cx + c * scale + dx, startY + r * scale + dy, color);
            }
          }
        }
      }
    }

    cx += (charWidth + spacing) * scale;
  }
}

function getTextWidth(str, scale = 1) {
  return str.length * (5 + 1) * scale;
}

module.exports = { renderText, getTextWidth };
